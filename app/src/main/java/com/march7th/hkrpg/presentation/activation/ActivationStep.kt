package com.march7th.hkrpg.presentation.activation

/**
 * 激活向导的步骤。
 *
 * ## 为什么要这个向导
 *
 * 崩铁助手要在 Android 上跑起来，必须满足几个硬条件：
 *
 * 1. **Shizuku 或 Root** —— 没有提权就拿不到虚拟屏和输入注入，
 *    整个后台化方案不成立。
 * 2. **虚拟屏能建起来** —— 这是崩铁跑在固定 1920×1080 上的前提，
 *    也是所有坐标/模板能全局复用的原因。
 * 3. **游戏包名选对** —— 国服 `com.miHoYo.hkrpg` 和
 *    国际服 `com.HoYoverse.hkrpgoversea` 是两个包。
 *
 * 原来这些东西散落在首页各张卡片里，用户得自己一个个点、
 * 还得猜"我到底缺哪一步"。现在改成手机开箱那种**一步一件事**的
 * 全屏向导：做完当前这步才放行下一步，全部做完才进主界面。
 *
 * ## 和「聚光灯引导」的区别
 *
 * 项目里另有一套 `presentation/onboarding` 的聚光灯引导 ——
 * 那个是**参观介绍**（高亮已有 UI，随时可跳过）。
 * 本向导是**强制激活**：跳过按钮只在非必需步骤出现。
 */
enum class ActivationStep {
    /** 欢迎页：说明这个 App 干什么、需要什么权限。 */
    WELCOME,

    /**
     * **用户协议与免责声明**（强制阅读 7 秒才能继续）。
     *
     * ## 为什么必须放在这个位置
     *
     * 它在「欢迎」之后、「选择提权方式」之前 —— 也就是用户
     * **还没授予任何高权限、还没让程序碰游戏**的时候就摊开说清楚：
     *
     * - 第三方自动化工具存在封号风险，风险由使用者自担；
     * - 本工具不修改游戏文件、不注入进程，但**不对账号安全作任何承诺**；
     * - 不要在米游社等官方社区讨论本工具（容易被判定为外挂宣传）；
     * - 明确列出会申请的权限与用途。
     *
     * ## 为什么强制看 7 秒
     *
     * 这类免责声明如果做成"直接点下一步"，99% 的用户根本不会看。
     * 强制倒计时是这个场景的通行做法（用户至少会扫一眼标题和首段）。
     *
     * ⚠️ 不提供"跳过" —— 这是唯一不可跳过的步骤。
     */
    AGREEMENT,

    /** 选提权方式：Shizuku 还是 Root。 */
    BACKEND,

    /** 授予提权 + 必需权限。 */
    PERMISSION,

    /** 选游戏客户端（国服 / 国际服）。 */
    CLIENT,

    /** 完成。 */
    DONE,
}
