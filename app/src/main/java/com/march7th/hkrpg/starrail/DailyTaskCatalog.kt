    /** 按名字查任务定义。 */
    fun find(name: String): Task? = TASKS.firstOrNull { it.name == name }

    /** 从一行 OCR 文字里认出是哪个任务（返回标准任务名）。 */
    fun matchTask(rawText: String): String? {
        val t = rawText.replace(" ", "").replace("\u3000", "")
        return KEYWORD_TO_TASK.firstOrNull { (kw, _) ->
            t.contains(kw.replace(" ", ""))
        }?.second
    }
}
