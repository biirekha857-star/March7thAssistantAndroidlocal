        Task("将任意角色等级提升1次", 100, Support.DETECT_ONLY),
        Task("将任意遗器等级提升1次", 100, Support.DETECT_ONLY),
        Task("将任意光锥等级提升1次", 100, Support.DETECT_ONLY),
