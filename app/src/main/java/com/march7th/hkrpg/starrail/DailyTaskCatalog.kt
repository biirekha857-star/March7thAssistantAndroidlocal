package com.march7th.hkrpg.starrail

/**
 * 每日实训的**任务知识库**。
 *
 * 对齐原项目（March7thAssistant）的两个文件：
 *
 * | 原项目 | 本文件 |
 * |---|---|
 * | `assets/config/task_mappings.json` | [KEYWORD_TO_TASK] |
 * | `tasks/daily/daily.py` 的 `task_functions` | [TASKS] |
 *
 * # 为什么需要这张表
 *
 * 崩铁**每个号每天刷到的实训任务是不同的**（从一个大池子里随机抽 5 个）。
 *
 * 所以不能"固定顺序全做一遍"，必须：
 *
 * ```
 * ① 扫出今天实际有哪 5 个任务
 * ② 把**已经完成**的那些分数加起来
 * ③ 按优先级补齐剩下的，**够 500 就停**
 * ```
 *
 * 这张表提供 ③ 需要的两样东西：**每个任务值多少分**、**用什么顺序做**。
 *
 * # 优先级从哪来
 *
 * 原项目 `task_functions` 是 Python 字典，**书写顺序即执行顺序**：
 * 越靠前越容易做。本文件 [TASKS] 的列表顺序与之保持一致。
 */
internal object DailyTaskCatalog {

    /** 达成 500 活跃度的目标分数。 */
    const val TARGET_SCORE = 500

    /**
     * OCR 文本里的**关键词** → 标准任务名。
     *
     * ## 为什么要做这层映射
     *
     * 卡片上的任务名很长（「完成1次「拟造花萼（金）」」），
     * OCR 经常只认出其中几个字，或者把括号认成别的符号。
     *
     * 所以用**短关键词**去匹配：只要卡片文字里出现「金」，
     * 就认为它是「完成1次『拟造花萼（金）』」。
     *
     * ## ⚠️ 顺序敏感
     *
     * 必须是**更具体的关键词排在前面**。例如：
     * - 「拟造花萼（金）」要排在「拟造花萼」之前
     * - 「差分宇宙」要排在「模拟宇宙」之前
     *
     * 否则「完成1次『差分宇宙』或『模拟宇宙』」会被「模拟宇宙」抢先匹配成
     * 「通关模拟宇宙」那个 500 分任务，分数就算错了。
     */
    val KEYWORD_TO_TASK: List<Pair<String, String>> = listOf(
        // —— 每日实训里最常见的几条，关键词要足够独特 ——
        "登录游戏" to "登录游戏",
        "委托" to "派遣委托或收取1次委托奖励",
        "120点开拓力" to "累计消耗120点开拓力",
        "支援角色" to "使用支援角色并获得战斗胜利1次",

        // 副本类：用更长的词避免误配
        "拟造花萼（金）" to "完成1次「拟造花萼（金）」",
        "拟造花萼（赤）" to "完成1次「拟造花萼（赤）」",
        "凝滞虚影" to "完成1次「凝滞虚影」",
        "侵蚀隧洞" to "完成1次「侵蚀隧洞」",
        "历战余响" to "完成1次「历战余响」",

        // 角色/装备成长
        "角色等级" to "将任意角色等级提升1次",
        "遗器等级" to "将任意遗器等级提升1次",
        "光锥等级" to "将任意光锥等级提升1次",
        "分解任意1件遗器" to "分解任意1件遗器",
        "日常任务" to "完成1个日常任务",

        // 战斗类
        "消灭20个敌人" to "累计消灭20个敌人",
        "万能合成机" to "使用1次「万能合成机」",
        "拍照" to "拍照1次",
        "秘技" to "累计施放2次秘技",
        "可破坏物" to "累计击碎3个可破坏物",
        "忘却之庭" to "完成1次「忘却之庭」",
        "3种不同属性" to "单场战斗中，触发3种不同属性的弱点击破",
        "弱点击破效果5次" to "累计触发弱点击破效果5次",
        "利用弱点进入战斗" to "利用弱点进入战斗并获胜3次",
        "终结技" to "施放终结技造成制胜一击1次",

        // ## 助燃券 / 深度沉浸器
        //
        // 实测日志里出现过这条：「使用1次「助燃券」或「深度沉浸器」」。
        // 用「助燃券」当关键词（另一个分支的「深度沉浸器」也一起认）。
        "助燃券" to "使用1次「助燃券」或「深度沉浸器」",
        "深度沉浸器" to "使用1次「助燃券」或「深度沉浸器」",

        // ## 宇宙类：注意顺序！差分/货币战争要排在模拟宇宙之前
        //
        // ⚠️ OCR 常把「宇宙」认成「字画」「字由」之类。
        // 所以关键词取**两侧都不用「宇宙」**的片段。
        "差分字画" to "完成1次「差分宇宙」或「货币战争」",     // OCR 误识
        "货币战" to "完成1次「差分宇宙」或「货币战争」",
        "差分宇宙」或「货币战争" to "完成1次「差分宇宙」或「货币战争」",
        "差分宇宙」或「模拟宇宙" to "完成1次「差分宇宙」或「模拟宇宙」",
        "模拟宇宙」的1个区域" to "通关「模拟宇宙」（任意世界）的1个区域",
        "模拟宇宙" to "通关「模拟宇宙」（任意世界）的1个区域",
    )

    /**
     * 一条实训任务。
     *
     * @param name    标准任务名（与 [KEYWORD_TO_TASK] 的 value 一致）
     * @param score   完成后能拿多少活跃度
     * @param support 本实现能不能主动去做
     */
    data class Task(
        val name: String,
        val score: Int,
        val support: Support,
    )

    /** 本实现对某个任务的支持程度。 */
    enum class Support {
        /** 能主动完成 —— 会真的去操作游戏 */
        CAN_DO,

        /**
         * 只检测不执行。
         *
         * 这些任务要么是**累积型**（体力、支援、敌人数量），
         * 要么是**别处顺手就做了**（副本类的多半清体力时已完成），
         * 强行去刷反而浪费体力。
         *
         * 和原项目一样：这些任务如果扫到已完成，就直接把分算上；
         * 没完成也不主动做。
         */
        DETECT_ONLY,
    }

    /**
     * 全部任务，**按优先级排列**（越前越容易做）。
     *
     * 顺序对齐原项目 `tasks/daily/daily.py:240-276` 的 `task_functions`。
     */
